const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const { timingSafeEqual } = require('node:crypto');

// The capability lives only for this service run; other apps cannot use the local API.
function authorized(request, port, token) {
    if (!token || token.length !== 64 || request.headers.host !== `127.0.0.1:${port}`) return false;
    const origin = request.headers.origin;
    if (origin && origin !== `http://127.0.0.1:${port}`) return false;
    const cookie = (request.headers.cookie || '').split(';').map(x => x.trim()).find(x => x.startsWith('lh_android='));
    const actual = Buffer.from(cookie?.slice('lh_android='.length) || '');
    const expected = Buffer.from(token);
    return actual.length === expected.length && timingSafeEqual(actual, expected);
}

module.exports = { authorized };

if (require.main === module) {
    const port = Number(process.env.PORT);
    const token = process.env.LH_ANDROID_TOKEN;
    if (!Number.isInteger(port) || port < 1024 || !token || token.length !== 64) throw new Error('Missing Android runtime capability');
    const emit = http.Server.prototype.emit;
    http.Server.prototype.emit = function (event, ...args) {
        if ((event === 'request' || event === 'upgrade') && this.address()?.port === port && !authorized(args[0], port, token)) {
            if (event === 'upgrade') args[1].destroy();
            else { args[1].writeHead(403, { 'Cache-Control': 'no-store' }); args[1].end('Open LearnHarness from its app.'); }
            return true;
        }
        return emit.call(this, event, ...args);
    };
    // ZIP assets cannot carry the package-directory symlinks generated by Turbopack.
    for (const [relative, link] of Object.entries(require('./android-symlinks.json'))) {
        const target = path.join(__dirname, relative);
        fs.mkdirSync(path.dirname(target), { recursive: true });
        try { fs.symlinkSync(link, target); } catch (error) { if (error.code !== 'EEXIST') throw error; }
    }
    process.chdir(__dirname);
    import('./server.js').catch(error => { console.error(error); process.exit(1); });
}
